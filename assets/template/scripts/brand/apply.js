// npm run brand -- apply [--palette N] [--fonts N] [--logo <id>] [--icon-style gradient|solid|night|paper|ink] [--icon-scale 0.56]
// Writes the client's choices into brand/tokens.json, the ONE source of the brand colours and fonts:
//   --palette N   option N of out/brand/palette/palettes.json   (colours, ramp, neutrals, UI tokens, field)
//   --fonts N     pair N of out/brand/fonts/fonts.json           (display + text, headline weight)
//   --logo id     brand/logo-options/<id>.svg -> brand/logo.svg, <id>.mark.svg -> brand/mark.svg
//                 (the old files are kept in out/brand/previous/)
//   brand/icon.svg is (re)derived from brand/mark.svg with the token colours whenever it was generated
//   by this tool (or is missing); a hand-made icon (<id>.icon.svg, or no "generated" note) is left alone:
//   --logo <id> copies <id>.icon.svg when it exists and then derives nothing (only --icon-style / --icon-scale
//   replace a hand-made icon).
// Then: studio.config.js reads it through brand.tokens, the mock screens through <meta name="kit-tokens">.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../lib/cli.js';
import { overrides } from '../lib/tokens.js';
import { readBrief } from './lib/brief.js';
import { makeIcon } from './lib/icon.js';
import { TOKENS, OUT, readJson, writeJson, paletteTokens, fontTokens, mergeTokens, today } from './lib/tokens-io.js';

const val = (v) => (v === undefined || v === true ? null : String(v));
const abs = (rel) => path.join(ROOT, rel);
const GENERATED = /generated by npm run brand/;
const STYLES = ['gradient', 'solid', 'night', 'paper', 'ink'];

function pickOption(file, key, n, what) {
  const data = readJson(file, null);
  if (!data) throw new Error(`${file} not found: run npm run brand -- ${what} first`);
  const hit = (data[key] || []).find((o) => String(o.id) === String(n));
  if (!hit || hit.missing) throw new Error(`--${what} ${n}: ${file} has ${(data[key] || []).filter((o) => !o.missing).map((o) => o.id).join(', ')}`);
  return { data, hit };
}

function copyLogo(id, dirRel) {
  const files = [[`${id}.svg`, 'brand/logo.svg'], [`${id}.mark.svg`, 'brand/mark.svg'], [`${id}.icon.svg`, 'brand/icon.svg']];
  if (!fs.existsSync(abs(`${dirRel}/${id}.svg`))) throw new Error(`--logo ${id}: ${dirRel}/${id}.svg not found`);
  const done = [];
  for (const [from, to] of files) {
    if (!fs.existsSync(abs(`${dirRel}/${from}`))) continue;
    if (fs.existsSync(abs(to))) {
      fs.mkdirSync(abs(`${OUT}/previous`), { recursive: true });
      fs.copyFileSync(abs(to), abs(`${OUT}/previous/${path.basename(to)}`));
    }
    fs.copyFileSync(abs(`${dirRel}/${from}`), abs(to));
    done.push(`${dirRel}/${from} -> ${to}`);
  }
  return done;
}

function deriveIcon(tokens, cfg, force) {
  const icon = cfg.icon.src;
  const markRel = cfg.brand.mark || 'brand/mark.svg';
  const current = fs.existsSync(abs(icon)) ? fs.readFileSync(abs(icon), 'utf8') : '';
  if (current && !GENERATED.test(current) && !force) return `kept ${icon} (hand-made: pass --icon-style to replace it)`;
  if (!/\.svg$/.test(icon)) return `kept ${icon} (not an SVG)`;
  if (!fs.existsSync(abs(markRel))) return `no ${markRel}: icon not derived`;
  const opts = { style: (tokens.icon && tokens.icon.style) || 'gradient', scale: (tokens.icon && tokens.icon.scale) || 0.56 };
  if (current && !GENERATED.test(current)) {
    fs.mkdirSync(abs(`${OUT}/previous`), { recursive: true });
    fs.writeFileSync(abs(`${OUT}/previous/${path.basename(icon)}`), current);
  }
  fs.writeFileSync(abs(icon), makeIcon(fs.readFileSync(abs(markRel), 'utf8'), tokens.colors, opts));
  return `${icon} derived from ${markRel} (${opts.style}, scale ${opts.scale})`;
}

export async function run(flags, { cfg, raw, tokens }) {
  const brief = readBrief();
  const base = tokens || readJson(TOKENS, null) || {};
  const parts = [];
  if (val(flags.palette)) {
    const { data, hit } = pickOption(`${OUT}/palette/palettes.json`, 'options', flags.palette, 'palette');
    parts.push(paletteTokens(hit, data));
  }
  if (val(flags.fonts)) parts.push(fontTokens(pickOption(`${OUT}/fonts/fonts.json`, 'pairs', flags.fonts, 'fonts').hit));
  const iconStyle = val(flags['icon-style']);
  const iconScale = val(flags['icon-scale']);
  if (iconStyle && !STYLES.includes(iconStyle)) throw new Error(`--icon-style: ${STYLES.join(', ')}`);
  if (iconStyle || iconScale) parts.push({ icon: { ...(base.icon || {}), ...(iconStyle ? { style: iconStyle } : {}), ...(iconScale ? { scale: Number(iconScale) } : {}) } });
  const logo = val(flags.logo);
  if (!parts.length && !logo) {
    console.log(`apply: nothing to apply. Current ${TOKENS}: ${base.source ? JSON.stringify(base.source) : 'none yet'}`);
    console.log(`  npm run brand -- apply --palette N --fonts N [--logo <id>] [--icon-style ${STYLES.join('|')}]`);
    return;
  }
  // the project's name wins over whatever an older token file says (a copied template, a renamed app)
  const next = mergeTokens({ ...base, name: brief.name || cfg.brand.name || base.name }, ...parts, logo ? { source: { logo } } : {});
  if (!next.colors) throw new Error('no colours yet: apply a palette first (--palette N)');
  // tokens from another brand (a template copied without its setup clean-up): its logo is not this project's
  const foreign = base.name && next.name !== base.name && !logo && next.source && next.source.logo;
  if (foreign) delete next.source.logo;
  next.updated = today();
  writeJson(TOKENS, next);
  console.log(`apply -> ${TOKENS}   (name ${next.name})`);
  console.log(`  colours  ${next.source.palette || '(unchanged)'}   fonts  ${next.source.fonts || '(config)'}   field ${next.field}`);
  const copied = logo ? copyLogo(logo, val(flags.dir) || 'brand/logo-options') : [];
  for (const line of copied) console.log(`  logo     ${line}`);
  if (foreign) console.log(`  logo     brand/logo.svg was made for "${base.name}": the boards show "${next.name}" as text until apply --logo <id>`);
  // a hand-drawn <id>.icon.svg was just copied: keep it (a new mark without one re-derives the icon)
  const handIcon = copied.some((l) => /\.icon\.svg -> /.test(l));
  const icon = foreign ? 'not derived: it waits for this project\'s logo (apply --logo <id>)'
    : handIcon && !(iconStyle || iconScale) ? `kept the hand-drawn ${logo}.icon.svg` : deriveIcon(next, cfg, !!(iconStyle || iconScale || logo));
  console.log(`  icon     ${icon}`);

  const cfgReads = raw.brand && raw.brand.tokens === TOKENS;
  console.log(cfgReads ? `  config   studio.config.js reads ${TOKENS}` : `  config   add  tokens: '${TOKENS}'  to brand in studio.config.js so the store images use it`);
  const over = overrides(raw, next);
  if (over.length) console.log(`  note     studio.config.js overrides: ${over.join(', ')} (remove them to use the tokens)`);
  const screens = fs.existsSync(abs('screens')) ? fs.readdirSync(abs('screens')).filter((f) => f.endsWith('.html')) : [];
  const meta = screens.filter((f) => /name="kit-tokens"/.test(fs.readFileSync(abs(`screens/${f}`), 'utf8')));
  if (screens.length) console.log(`  screens  ${meta.length} of ${screens.length} mock screens read the tokens (<meta name="kit-tokens" content="/${TOKENS}">)`);
  console.log('\n  next: npm run brand -- board   (re-run npm run screens and npm run export after a change)\n');
}
