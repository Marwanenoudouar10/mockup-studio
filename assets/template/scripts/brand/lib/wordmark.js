// The quick logo (npm run brand -- apply --logo wordmark): for a job without a logo step, a lockup and a symbol
// made from the brand name in the display font, so the panels, the boards and the store icons have a real logo:
//   brand/logo-options/wordmark.svg       the name as live text (textLength measured in the font) + an accent dot
//   brand/logo-options/wordmark.mark.svg  the initial as outlines (an icon is an <img>: it cannot load the font)
//                                         + the same dot, for the app icon (lib/icon.js) and the watermark
// Measured and outlined with fontkit (an optional dependency) from the installed fontsource files; without it the
// width is estimated and the symbol is the initial as text. A file without the "generated" note is hand-made and
// is never overwritten.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../../lib/cli.js';
import { findFont } from './fontsource.js';
import { fontAt } from '../../lib/outline.js';

export const GENERATED_WORDMARK = 'generated by npm run brand -- apply --logo wordmark';
const SIZE = 80;
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const r1 = (n) => Math.round(n * 10) / 10;

// the installed file of a family at (or nearest to) a weight -> Buffer | null
function fontFile(family, weight) {
  const f = findFont(family);
  if (f.missing) return null;
  const slug = f.package.split('/')[1];
  const dir = path.join(ROOT, 'node_modules', f.package, 'files');
  const w = f.weights.reduce((a, b) => (Math.abs(b - weight) < Math.abs(a - weight) ? b : a), f.weights[0]);
  const names = f.variable ? [`${slug}-latin-wght-normal.woff2`] : [`${slug}-latin-${w}-normal.woff`, `${slug}-latin-${w}-normal.woff2`];
  const hit = names.map((n) => path.join(dir, n)).find((p) => fs.existsSync(p));
  return hit ? fs.readFileSync(hit) : null;
}

function metrics(family, weight) {
  try {
    const buf = fontFile(family, weight);
    return buf ? fontAt(buf, weight) : null;
  } catch {
    return null; // fontkit not installed, or a face it cannot read
  }
}

// -> { logo, mark } SVG texts
export function makeWordmark({ name, family, weight = 700 }) {
  const font = metrics(family, weight);
  const text = String(name || 'App').trim();
  const k = font ? SIZE / font.unitsPerEm : 0;
  const track = -0.02 * SIZE;
  const width = font ? font.layout(text).positions.reduce((a, p) => a + p.xAdvance, 0) * k + track * (text.length - 1) : text.length * 0.6 * SIZE;
  const asc = font ? font.ascent * k : SIZE * 0.95;
  const desc = font ? -font.descent * k : SIZE * 0.25;
  const dot = SIZE * 0.13;
  const W = r1(width + dot * 3.2);
  const H = r1(asc + desc);
  const fam = `var(--font-display, '${family}', sans-serif)`;
  const note = `<desc>${GENERATED_WORDMARK}: the name in ${esc(family)} ${weight} and one accent dot. Replace it with a drawn logo when there is one.</desc>`;
  const logo = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" fill="currentColor">\n  <title>${esc(text)} wordmark</title>\n  ${note}\n`
    + `  <text x="0" y="${r1(asc)}" textLength="${r1(width)}" lengthAdjust="spacing" style="font-family: ${fam}; font-weight: ${weight}; font-size: ${SIZE}px; letter-spacing: ${r1(track)}px">${esc(text)}</text>\n`
    + `  <circle cx="${r1(width + dot * 1.9)}" cy="${r1(asc - dot)}" r="${r1(dot)}" style="fill: var(--accent)"/>\n</svg>\n`;
  const initial = [...text][0].toUpperCase();
  let glyph = `<text x="0" y="${r1(asc)}" style="font-family: ${fam}; font-weight: ${weight}; font-size: ${SIZE}px">${esc(initial)}</text>`;
  let gw = 0.62 * SIZE;
  if (font && font.hasGlyphForCodePoint(initial.codePointAt(0))) {
    const run = font.layout(initial);
    const g = run.glyphs[0];
    gw = run.positions[0].xAdvance * k;
    glyph = `<path d="${g.path.scale(k, -k).translate(0, asc).toSVG().replace(/-?\d+\.\d+/g, (v) => String(r1(+v)))}"/>`;
  }
  const MW = r1(gw + dot * 3);
  const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${MW} ${H}" fill="currentColor">\n  <title>${esc(text)} monogram</title>\n  ${note}\n`
    + `  ${glyph}\n  <circle cx="${r1(gw + dot * 1.6)}" cy="${r1(asc - dot)}" r="${r1(dot)}" style="fill: var(--accent)"/>\n</svg>\n`;
  return { logo, mark };
}

// writes the two files unless hand-made ones are there -> lines for the log
export function writeWordmark(dirRel, opts) {
  const dir = path.join(ROOT, dirRel);
  const files = [['wordmark.svg', 'logo'], ['wordmark.mark.svg', 'mark']];
  const own = files.filter(([f]) => fs.existsSync(path.join(dir, f)) && !fs.readFileSync(path.join(dir, f), 'utf8').includes(GENERATED_WORDMARK));
  if (own.length) return [`kept the hand-made ${own.map(([f]) => `${dirRel}/${f}`).join(', ')}`];
  const svg = makeWordmark(opts);
  fs.mkdirSync(dir, { recursive: true });
  for (const [f, k] of files) fs.writeFileSync(path.join(dir, f), svg[k]);
  return [`${dirRel}/wordmark.svg + wordmark.mark.svg made from "${opts.name}" in ${opts.family} ${opts.weight}`];
}
