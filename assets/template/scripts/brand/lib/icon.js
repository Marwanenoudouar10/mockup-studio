// The app icon, derived from the chosen symbol: a full-bleed 1024 square (no rounded corners, no
// transparency: the App Store and Google Play apply their own mask) with the brand colours behind it
// and the symbol centred inside the safe area.
//   style  gradient (default) | solid | night | paper        scale  symbol width / icon width (0.56)
// The symbol keeps currentColor (white, or the primary on paper) and var(--accent) from the tokens.
// Safe area: keep the symbol inside the centre 66% circle so Android's round mask never cuts it.
const parseAttrs = (s) => Object.fromEntries([...s.matchAll(/([\w:-]+)\s*=\s*"([^"]*)"/g)].map((m) => [m[1], m[2]]));

export function readSvg(text) {
  const clean = text.replace(/<\?xml[\s\S]*?\?>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  const open = clean.match(/<svg\b([^>]*)>/i);
  const end = clean.lastIndexOf('</svg>');
  if (!open || end < 0) throw new Error('not an SVG file');
  const attrs = parseAttrs(open[1]);
  const vb = (attrs.viewBox || `0 0 ${parseFloat(attrs.width) || 100} ${parseFloat(attrs.height) || 100}`).split(/[\s,]+/).map(Number);
  const inner = clean.slice(open.index + open[0].length, end).replace(/<(title|desc)>[\s\S]*?<\/\1>/g, '')
    .split('\n').map((l) => l.trim()).filter(Boolean).join('');
  return { attrs, vb, inner };
}

// "--" inside an XML comment makes the whole file invalid XML (browsers then refuse to inline it).
export function svgProblems(text) {
  const bad = [];
  for (const m of text.matchAll(/<!--([\s\S]*?)-->/g)) if (m[1].includes('--')) bad.push('a comment contains "--" (invalid XML)');
  if (!/viewBox=/.test(text)) bad.push('no viewBox (it will not scale)');
  return bad;
}

export const titleOf = (text) => {
  const t = text.match(/<title>([^<]*)<\/title>/);
  const d = text.match(/<desc>([^<]*)<\/desc>/);
  return { title: t ? t[1].trim() : '', desc: d ? d[1].trim().replace(/\s+/g, ' ') : '' };
};

function background(style, c) {
  if (style === 'paper') return { fill: c.paper, glow: c.primary, glowOpacity: 0.1, mark: c.primary };
  if (style === 'solid') return { fill: c.primary, glow: '#FFFFFF', glowOpacity: 0.16, mark: c.onField || '#FFFFFF' };
  if (style === 'night') return { stops: [c.secondary, c.deep, c.deep], glow: c.primary, glowOpacity: 0.5, mark: '#FFFFFF' };
  return { stops: [c.primary, c.primary, c.secondary], glow: '#FFFFFF', glowOpacity: 0.24, mark: c.onField || '#FFFFFF' };
}

export function makeIcon(markText, colors, { style = 'gradient', scale = 0.56 } = {}) {
  const { attrs, vb, inner } = readSvg(markText);
  const bg = background(style, colors);
  const S = 1024;
  const ar = vb[3] / vb[2];
  const w = ar > 1 ? (S * scale) / ar : S * scale;
  const h = w * ar;
  const keep = Object.entries(attrs).filter(([k]) => !/^(xmlns(:\w+)?|width|height|x|y|viewBox|style|class|id)$/.test(k));
  const own = keep.map(([k, v]) => ` ${k}="${v}"`).join('');
  const ids = inner.replace(/\bid="([^"]+)"/g, 'id="m-$1"').replace(/url\(#([^)]+)\)/g, 'url(#m-$1)').replace(/href="#([^"]+)"/g, 'href="#m-$1"');
  const fill = bg.stops
    ? `<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${bg.stops[0]}"/>`
      + `<stop offset=".5" stop-color="${bg.stops[1]}"/><stop offset="1" stop-color="${bg.stops[2]}"/></linearGradient>`
    : '';
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}">`,
    `  <!-- App icon generated by npm run brand (style ${style}, scale ${scale}). Full-bleed: the stores round it. -->`,
    `  <defs>${fill}<radialGradient id="glow" cx=".28" cy=".16" r=".75"><stop offset="0" stop-color="${bg.glow}" stop-opacity="${bg.glowOpacity}"/>`
      + `<stop offset="1" stop-color="${bg.glow}" stop-opacity="0"/></radialGradient></defs>`,
    `  <rect width="${S}" height="${S}" fill="${bg.stops ? 'url(#bg)' : bg.fill}"/>`,
    `  <rect width="${S}" height="${S}" fill="url(#glow)"/>`,
    `  <g style="color: ${bg.mark}; --accent: ${colors.accent}; --primary: ${colors.primary}">`,
    `    <svg x="${((S - w) / 2).toFixed(1)}" y="${((S - h) / 2).toFixed(1)}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" viewBox="${vb.join(' ')}"${own}>${ids}</svg>`,
    '  </g>',
    '</svg>',
    '',
  ].join('\n');
}
